def _center_text_safe(pdf, text, size=11):
    """Print centered text, truncating if too long."""
    max_chars = 65
    if len(text) > max_chars:
        text = text[:max_chars - 3] + "..."
    pdf.cell(0, 8, text, align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)


