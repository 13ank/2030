#  PDF report
# ─────────────────────────────────────────────────────────────────────────────
def _save_pdf_report(pdf_path, url, date, risk_summary, findings, scan_results):
    pdf = SecurityReport(url, date)
    pdf.add_page()

    # Page 1: Cover
    _draw_cover(pdf, url, date, risk_summary)

    # Page 2: Executive Summary
    pdf.add_page()
    _draw_exec_summary(pdf, url, risk_summary, findings, scan_results)

    # Page 3+: Findings
    if findings:
        pdf.add_page()
        _draw_findings_section(pdf, findings)

    # Last page: Appendix (tool status)
    pdf.add_page()
    _draw_appendix(pdf, scan_results, risk_summary)

    pdf.output(pdf_path)


