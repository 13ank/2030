def _draw_appendix(pdf, scan_results, risk_summary):
    _section_header(pdf, "APPENDIX -- SCAN MODULE SUMMARY")

    for tool_name, data in scan_results.items():
        status = data.get("status", "unknown")
        if status == "success":
            status_col = (50, 180, 50)
        elif status == "error":
            status_col = (220, 38, 38)
        else:
            status_col = (200, 150, 0)

        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(*COL_BG_DARK)
        pdf.set_x(20)
        pdf.cell(0, 7, f"  {tool_name.upper()}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Status
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(*COL_TEXT_DARK)
        pdf.set_x(24)
        pdf.set_text_color(*status_col)
        pdf.cell(0, 5, f"Status: {status.capitalize()}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Findings count
        n = len(data.get("findings", []))
        pdf.set_text_color(*COL_TEXT_DARK)
        pdf.set_x(24)
        pdf.cell(0, 5, f"Findings: {n}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Extra info per tool
        if tool_name == "nmap" and data.get("open_ports"):
            pdf.set_x(24)
            pdf.cell(0, 5, f"Open Ports: {', '.join(map(str, data['open_ports']))}",
                     new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        if tool_name == "gobuster" and data.get("paths"):
            pdf.set_x(24)
            pdf.cell(0, 5, f"Paths Discovered: {len(data['paths'])}",
                     new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        if tool_name == "whatweb" and data.get("technologies"):
            techs = ", ".join(t["name"] for t in data["technologies"][:8])
            pdf.set_x(24)
            pdf.multi_cell(166, 5, f"Technologies: {techs}")

        pdf.set_draw_color(*COL_LIGHT_GRAY)
        pdf.set_line_width(0.3)
        pdf.line(24, pdf.get_y() + 1, 190, pdf.get_y() + 1)
        pdf.ln(4)

    # Disclaimer
    pdf.ln(6)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(*COL_MID_GRAY)
    disclaimer = (
        "DISCLAIMER: This report was generated by an automated scanning system. "
        "Results may contain false positives. All findings should be manually verified "
        "before remediation. This report is intended for authorized security testing only."
    )
    pdf.multi_cell(0, 5, disclaimer)


