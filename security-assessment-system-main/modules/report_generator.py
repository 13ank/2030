def _draw_exec_summary(pdf, url, risk_summary, findings, scan_results):
    _section_header(pdf, "EXECUTIVE SUMMARY")

    counts    = risk_summary.get("counts", {})
    total     = sum(counts.values())
    total_risks = risk_summary.get("total_risks", 0)
    max_score = risk_summary.get("max_score", 0.0)
    # Summary text
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*COL_TEXT_DARK)
    summary_text = (
        f"An automated security assessment was conducted against the target: {url}. "
        f"The scan identified a total of {total} security findings across all scan modules, "
        f"representing {total_risks} distinct security risks (excluding INFO-level observations). "
        f"The maximum CVSS score identified is {max_score:.1f}/10, classified as {get_risk_label(max_score)}. "
        f"Immediate attention is required for any CRITICAL and HIGH severity findings."
    )
    pdf.multi_cell(0, 6, summary_text)
    pdf.ln(5)

    # Risk breakdown chart
    _section_subheader(pdf, "Finding Distribution")
    severities = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]
    bar_max_w  = 120
    max_count  = max((counts.get(s, 0) for s in severities), default=1) or 1

    for sev_name in severities:
        count   = counts.get(sev_name, 0)
        sev_col = SEV_COLORS.get(sev_name, (100, 116, 139))
        bar_w   = int((count / max_count) * bar_max_w) if count > 0 else 2

        # Severity label
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*sev_col)
        pdf.set_x(20)
        pdf.cell(22, 7, sev_name, align="L")

        # Bar
        pdf.set_fill_color(*sev_col)
        pdf.rect(pdf.get_x(), pdf.get_y() + 1, bar_w, 5, "F")

        # Count
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*COL_TEXT_DARK)
        pdf.set_x(pdf.get_x() + bar_w + 3)
        pdf.cell(15, 7, str(count), align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.ln(4)

    # Tools used
    _section_subheader(pdf, "Scan Modules")
    tool_statuses = []
    for tool, data in scan_results.items():
        status = data.get("status", "unknown")
        icon   = "[OK]" if status == "success" else ("[ERR]" if status == "error" else "[TMO]")
        tool_statuses.append(f"{icon} {tool.upper()}: {status.capitalize()}")

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*COL_TEXT_DARK)
    for i in range(0, len(tool_statuses), 2):
        left = tool_statuses[i]
        right = tool_statuses[i + 1] if i + 1 < len(tool_statuses) else ""
        pdf.set_x(20)
        pdf.cell(85, 6, left)
        pdf.cell(85, 6, right, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.ln(5)

    # Risk score visual gauge
    _section_subheader(pdf, "Max CVSS Score")
    _draw_score_gauge(pdf, max_score,
                      risk_summary.get("max_severity", "INFO"))


def _draw_score_gauge(pdf, score, severity):
    """Draw a horizontal risk gauge."""
    gauge_x, gauge_y = 20, pdf.get_y() + 2
    gauge_w, gauge_h = 170, 12

    # Background bar
    pdf.set_fill_color(*COL_LIGHT_GRAY)
    pdf.rect(gauge_x, gauge_y, gauge_w, gauge_h, "F")

    # Filled portion
    fill_w = int((score / 10.0) * gauge_w)
    sev_col = SEV_COLORS.get(severity, (100, 116, 139))
    if fill_w > 0:
        pdf.set_fill_color(*sev_col)
        pdf.rect(gauge_x, gauge_y, fill_w, gauge_h, "F")

    # Score label inside bar
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(*COL_WHITE)
    if fill_w > 20:
        pdf.set_xy(gauge_x + 4, gauge_y + 2)
        label = get_risk_label(score)
        pdf.cell(fill_w - 4, 8, f"{score:.1f} / 10  {label}", align="L")

    pdf.set_y(gauge_y + gauge_h + 4)

    # Tick marks
    pdf.set_font("Helvetica", "", 7)
    pdf.set_text_color(*COL_MID_GRAY)
    for tick in range(0, 11, 2):
        tx = gauge_x + int((tick / 10) * gauge_w)
        pdf.set_xy(tx - 3, pdf.get_y())
        pdf.cell(6, 4, str(tick), align="C")
    pdf.ln(6)


# ─────────────────────────────────────────────────────────────────────────────
#  Findings Section
# ─────────────────────────────────────────────────────────────────────────────
def _draw_findings_section(pdf, findings):
    _section_header(pdf, "DETAILED FINDINGS")

    # Group by severity
    severity_order = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]
    groups = {s: [] for s in severity_order}
    for f in findings:
        sev = f.get("severity", "INFO").upper()
        groups.get(sev, groups["INFO"]).append(f)

    finding_num = 1
    for sev_name in severity_order:
        group = groups[sev_name]
        if not group:
            continue

        sev_col = SEV_COLORS.get(sev_name, (100, 116, 139))
        sev_bg  = SEV_BG.get(sev_name, COL_LIGHT_GRAY)

        # Severity group header page break check
        if pdf.get_y() > 235:
            pdf.add_page()

        pdf.set_fill_color(*sev_bg)
        pdf.set_draw_color(*sev_col)
        pdf.set_line_width(0.3)
        pdf.rect(20, pdf.get_y(), 170, 10, "FD")
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(*sev_col)
        pdf.set_x(24)
        pdf.cell(160, 10, f"  {sev_name}  --  {len(group)} finding(s)",
                 align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(2)

        for f in group:
            _draw_finding_card(pdf, f, finding_num)
            finding_num += 1
            pdf.ln(3)

        pdf.ln(4)


def _draw_finding_card(pdf, finding, num):
    """Draw a single finding card."""
    sev_name = finding.get("severity", "INFO").upper()
    sev_col  = SEV_COLORS.get(sev_name, (100, 116, 139))
    sev_bg   = SEV_BG.get(sev_name, COL_LIGHT_GRAY)
    score    = finding.get("cvss_base_score", 0.0)
    title    = finding.get("title", "Unknown Finding")
    desc     = finding.get("description", "")
    evidence = finding.get("evidence", "")
    tool     = finding.get("tool", "")
    category = finding.get("category", "")
    cve      = finding.get("cve", "")
    vector   = finding.get("cvss_vector", "")

    # Estimate height needed for card to avoid awkward page breaks
    desc_lines = (len(desc) // 65) + 1 if desc else 0
    ev_lines   = (len(evidence) // 65) + 1 if evidence else 0
    est_height = 15 + (desc_lines * 5) + (ev_lines * 4.5) + (4 if vector else 0)

    # Page break check using estimated height
    if pdf.get_y() + est_height > 260:
        pdf.add_page()

    card_x = 20
    start_y = pdf.get_y()

    # Finding number + title
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(*COL_TEXT_DARK)
    pdf.set_xy(card_x + 6, start_y + 1)
    title_display = f"#{num:02d}  {title}"
    if len(title_display) > 80:
        title_display = title_display[:77] + "..."
    pdf.cell(120, 6, title_display, align="L")

    # CVSS score badge
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_fill_color(*sev_col)
    pdf.set_text_color(*COL_WHITE)
    pdf.set_xy(card_x + 130, start_y + 1)
    pdf.cell(36, 6, f"CVSS {score:.1f}  {sev_name}", fill=True, align="C",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_y(start_y + 8)

    # Meta row: tool | category | CVE
    meta_parts = [f"Tool: {tool.upper()}"]
    if category:
        meta_parts.append(f"Category: {category}")
    if cve:
        meta_parts.append(f"CVE: {cve}")
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.set_text_color(*COL_MID_GRAY)
    pdf.set_x(card_x + 6)
    pdf.cell(164, 5, "  |  ".join(meta_parts), align="L",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    # Description
    if desc:
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(*COL_TEXT_DARK)
        pdf.set_x(card_x + 6)
        desc_display = desc[:300] + ("..." if len(desc) > 300 else "")
        pdf.multi_cell(164, 5, desc_display)

    # Evidence
    if evidence:
        pdf.set_font("Helvetica", "I", 7.5)
        pdf.set_text_color(60, 80, 120)
        pdf.set_x(card_x + 6)
        ev_display = evidence[:150] + ("..." if len(evidence) > 150 else "")
        pdf.multi_cell(164, 4.5, f"Evidence: {ev_display}")

    # CVSS vector (if available)
    if vector:
        pdf.set_font("Helvetica", "I", 7)
        pdf.set_text_color(*COL_MID_GRAY)
        pdf.set_x(card_x + 6)
        pdf.cell(164, 4, f"CVSS Vector: {vector}", align="L",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    # Calculate actual card height and draw borders / accent
    end_y = pdf.get_y() + 1
    card_h = max(10.0, end_y - start_y) if end_y > start_y else est_height

    # Bottom border line
    pdf.set_draw_color(*sev_col)
    pdf.set_line_width(0.2)
    pdf.line(card_x + 4, end_y, card_x + 170, end_y)

    # Left severity stripe
    pdf.set_fill_color(*sev_col)
    pdf.rect(card_x, start_y, 4, card_h, "F")

    pdf.set_y(end_y + 2)


