# ─────────────────────────────────────────────────────────────────────────────
#  Custom FPDF class
# ─────────────────────────────────────────────────────────────────────────────
class SecurityReport(FPDF):
    def __init__(self, target_url: str, scan_date: str):
        super().__init__()
        self.target_url = target_url
        self.scan_date  = scan_date
        self.set_auto_page_break(auto=True, margin=20)
        self.set_margins(20, 20, 20)

    def header(self):
        if self.page_no() == 1:
            return
        # ── Running header ─────────────────────────────────────────────
        self.set_fill_color(*COL_BG_DARK)
        self.rect(0, 0, 210, 12, "F")
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(*COL_TEXT_LIGHT)
        self.set_xy(10, 3)
        self.cell(0, 6, "SECURITY ASSESSMENT REPORT", align="L")
        self.set_xy(0, 3)
        self.cell(200, 6, f"Page {self.page_no()}", align="R")
        self.set_text_color(*COL_TEXT_DARK)
        self.ln(14)

    def footer(self):
        if self.page_no() == 1:
            return
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(*COL_MID_GRAY)
        self.cell(0, 5, f"Target: {self.target_url}  |  {self.scan_date}  |  "
                        f"Generated by {config.REPORT_AUTHOR}", align="C")


# ─────────────────────────────────────────────────────────────────────────────
#  Main generation function
# ─────────────────────────────────────────────────────────────────────────────
def generate_report(
    url: str,
    scan_results: Dict[str, Any],
    risk_summary: Dict[str, Any],
    findings: List[Dict],
    output_dir: str,
    timestamp: str,
) -> Dict[str, str]:
    """
    Generate PDF and TXT reports.

    Returns:
        {"pdf": "...", "txt": "..."}
    """
    os.makedirs(output_dir, exist_ok=True)

    from urllib.parse import urlparse
    import re
    parsed = urlparse(url)
    host   = parsed.hostname or "target"
    host_clean = re.sub(r"[^\w.-]", "_", host)
    port_str   = f"_port{parsed.port}" if parsed.port else ""
    base_name  = f"report_{host_clean}{port_str}_{timestamp}"

    pdf_path = os.path.join(output_dir, f"{base_name}.pdf")
    txt_path = os.path.join(output_dir, f"{base_name}.txt")

    scan_date = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # -- TXT Report
    _save_txt_report(txt_path, url, scan_date, risk_summary, findings, scan_results)

    # -- PDF Report
    _save_pdf_report(pdf_path, url, scan_date, risk_summary, findings, scan_results)

    logger.info(f"Reports saved: {pdf_path}, {txt_path}")
    return {"pdf": pdf_path, "txt": txt_path}




# ─────────────────────────────────────────────────────────────────────────────
#  TXT report
# ─────────────────────────────────────────────────────────────────────────────
def _save_txt_report(path, url, date, risk_summary, findings, scan_results):
    """Generate a structured plain-text report readable in any terminal/editor."""
    SEP  = "=" * 70
    SEP2 = "-" * 70
    lines = []

    # ── Header ──────────────────────────────────────────────────────────────
    lines += [
        SEP,
        "  AUTOMATED SECURITY MISCONFIGURATION ASSESSMENT REPORT",
        f"  {config.REPORT_AUTHOR}  v{config.REPORT_VERSION}",
        SEP,
        f"  Target URL  : {url}",
        f"  Scan Date   : {date}",
        SEP,
        "",
    ]

    # ── Overall Risk Score ───────────────────────────────────────────────────
    max_score     = risk_summary.get("max_score", 0.0)
    overall_sev   = risk_summary.get("max_severity", "INFO")
    risk_label    = get_risk_label(max_score)
    counts        = risk_summary.get("counts", {})
    total         = sum(counts.values())
    total_risks   = risk_summary.get("total_risks", 0)

    lines += [
        "[OVERALL RISK ASSESSMENT]",
        SEP2,
        f"  Max CVSS Score     : {max_score:.1f} / 10",
        f"  Overall Risk Level : {risk_label.upper()}",
        f"  Total Findings     : {total}",
        f"  Total Risks        : {total_risks} (Excluding INFO)",
        "",
        "  Severity Breakdown:",
    ]
    severity_order = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]
    max_count = max((counts.get(s, 0) for s in severity_order), default=1) or 1
    for sev in severity_order:
        count   = counts.get(sev, 0)
        bar_len = int((count / max_count) * 30) if count > 0 else 0
        bar     = "|" * bar_len
        lines.append(f"    {sev:<10} {count:>4}  [{bar:<30}]")
    lines += ["", ""]

    # -- Scan Module Status
    lines += [
        "[SCAN MODULE STATUS]",
        SEP2,
    ]
    for tool_name, data in scan_results.items():
        status       = data.get("status", "unknown")
        n_findings   = len(data.get("findings", []))
        error_reason = data.get("error_reason", "")

        # Extract reason from raw_output if not set
        if status != "success" and not error_reason:
            raw = data.get("raw_output", "")
            if raw and raw.strip():
                error_reason = raw.strip().splitlines()[-1][:100]

        if status == "success":
            icon   = "[OK]   "
            detail = f"Findings: {n_findings}"
        elif status == "error":
            icon   = "[ERROR]"
            detail = f"FAILED  -- {error_reason}" if error_reason else "FAILED"
        elif status == "timeout":
            icon   = "[TMO]  "
            detail = f"TIMEOUT -- ran longer than allowed"
        else:
            icon   = "[???]  "
            detail = status

        lines.append(f"  {icon}  {tool_name.upper():<12} {detail}")

        # Extra per-tool info (only on success)
        if status == "success":
            if tool_name == "nmap" and data.get("open_ports"):
                ports_str = ", ".join(map(str, data["open_ports"]))
                lines.append(f"             Open Ports  : {ports_str}")
            if tool_name == "whatweb" and data.get("technologies"):
                techs = ", ".join(
                    f"{t['name']}{(' v' + t['version']) if t.get('version') else ''}"
                    for t in data["technologies"][:6]
                )
                lines.append(f"             Technologies: {techs}")
            if tool_name == "gobuster" and data.get("paths"):
                lines.append(f"             Paths Found : {len(data['paths'])}")
    lines += ["", ""]


    # ── Detailed Findings ────────────────────────────────────────────────────
    lines += [
        "[DETAILED FINDINGS]",
        SEP2,
    ]

    if not findings:
        lines.append("  No findings recorded.")
    else:
        groups = {s: [] for s in severity_order}
        for f in findings:
            sev = f.get("severity", "INFO").upper()
            groups.get(sev, groups["INFO"]).append(f)

        finding_num = 1
        for sev_name in severity_order:
            group = groups[sev_name]
            if not group:
                continue
            lines += [
                "",
                f"  >> {sev_name} ({len(group)} finding(s))",
                "  " + "-" * 60,
            ]
            for f in group:
                score    = f.get("cvss_base_score", 0.0)
                title    = f.get("title", "Unknown")
                tool     = f.get("tool", "").upper()
                category = f.get("category", "")
                desc     = f.get("description", "")
                evidence = f.get("evidence", "")
                vector   = f.get("cvss_vector", "")
                cve      = f.get("cve", "")

                lines += [
                    f"  [{finding_num:03d}] {title}",
                    f"       Severity : {sev_name}  |  CVSS Score: {score:.1f}",
                    f"       Tool     : {tool}  |  Category: {category}",
                ]
                if cve:
                    lines.append(f"       CVE      : {cve}")
                if desc:
                    # Wrap long descriptions
                    desc_lines = _wrap_text(desc, width=60, prefix="       ")
                    lines.append(f"       Desc     : {desc_lines[0].strip()}")
                    for dl in desc_lines[1:]:
                        lines.append(dl)
                if evidence:
                    ev_short = evidence[:100] + ("..." if len(evidence) > 100 else "")
                    lines.append(f"       Evidence : {ev_short}")
                if vector:
                    lines.append(f"       CVSS Vec : {vector}")
                lines.append("")
                finding_num += 1

    lines += [""]

    # ── Footer ───────────────────────────────────────────────────────────────
    lines += [
        SEP,
        "  DISCLAIMER: This report is generated by an automated scanning system.",
        "  Results may contain false positives. Verify all findings before remediation.",
        "  For authorized security testing purposes only.",
        SEP,
        "",
    ]

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def _wrap_text(text: str, width: int = 60, prefix: str = "") -> list:
    """Simple word-wrap for text in TXT report."""
    words = text.split()
    wrapped_lines = []
    current = ""
    for word in words:
        if len(current) + len(word) + 1 <= width:
            current = (current + " " + word).strip()
        else:
            if current:
                wrapped_lines.append(prefix + current)
            current = word
    if current:
        wrapped_lines.append(prefix + current)
    return wrapped_lines or [prefix]


